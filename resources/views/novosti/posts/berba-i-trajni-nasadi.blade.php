<p>
    AgroLog je dosad bio složen prvenstveno za ratarstvo. Sada je prikladan i za <strong>voćnjake, vinograde i maslinike</strong>: dobili smo Berbu i žetvu kao novu aktivnost te trajne nasade.
</p>

<h2>Berba i žetva</h2>
<p>
    Pod <strong>Aktivnosti → Berba i žetva</strong> upisujete datum, količinu, cijenu, sortu, klasu i kupca. Jedna kultura može imati koliko god berbi, a zapisi se mogu ispisati ili preuzeti kao CSV pod Izvještajima.
</p>

<h2>Upozorenje na karencu</h2>
<p>
    AgroLog datum berbe uspoređuje s upisanim prskanjima i registrom FIS-a. Ako karenca nije prošla, odmah vidite koje je sredstvo u pitanju i do kada karenca traje. Spremanje se ne blokira, a mjerodavna je etiketa sredstva.
</p>

<h2>Trajni nasadi</h2>
<p>
    Kulturu označite kao <strong>trajni nasad</strong>, po želji sa sortom, godinom sadnje i brojem stabala. Nasad zauzima površinu parcele iz godine u godinu, dok ga ne označite kao iskrčen. Potpore i ostale troškove upisujete za svaku godinu posebno.
</p>

<h2>Dobit po hektaru</h2>
<p>
    Stranica Troškovi prihod sada računa iz upisanih berbi u odabranom razdoblju. Kultura bez berbi i dalje koristi ručni upis prinosa. Više u <a href="{{ route('docs') }}#berba">Uputama</a>.
</p>
