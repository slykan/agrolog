<p>
    Istekla registracija traktora, zaboravljeno osiguranje prikolice ili prskalica bez važećeg pregleda znače kaznu na cesti ili pri kontroli.
    AgroLog sada ima <strong>Mehanizaciju</strong>: upišete strojeve i vozila i do kada vrijedi koji rok, a AgroLog vas mailom podsjeti na vrijeme.
</p>

<h2>Što se upisuje</h2>
<ul>
    <li><strong>Strojevi i vozila:</strong> traktor, kombajn, prskalica, rasipač, priključci, prikolica, osobno ili teretno vozilo. Uz to registracija, godina i serijski broj.</li>
    <li><strong>Rokovi:</strong> registracija, tehnički pregled, osiguranje (AO i kasko), servis, pregled prskalice ili rasipača, ili bilo koji svoj rok (npr. baždarenje).</li>
    <li><strong>Servisna knjiga:</strong> datum, što je rađeno, radni sati (motosati), trošak i serviser.</li>
</ul>

<h2>Podsjetnik mailom</h2>
<p>
    Zadano 30 dana prije isteka stiže mail s popisom onoga što ističe, a ako rok prođe, još jedan. Za svaki rok možete izabrati
    7, 14, 30, 60 ili 90 dana unaprijed, ili ga ostaviti bez podsjetnika. Isti popis je i na početnoj stranici.
</p>

<h2>Obnovljeno jednim klikom</h2>
<p>
    Kad registrirate traktor ili obavite pregled, kliknite <strong>Obnovljeno</strong>. AgroLog predloži sljedeći datum:
    registracija, tehnički, osiguranje i servis +1 godina, pregled prskalice +3 godine. Stari rok ostaje u povijesti stroja.
    Kad upišete servis, rok sljedećeg servisa se sam pomakne godinu dana od datuma servisa.
</p>
<p class="text-sm text-gray-500">
    Pregled uređaja za primjenu pesticida (prskalica, raspršivača) obavezan je periodično, u pravilu svake tri godine. Točan rok piše na naljepnici i u zapisniku zadnjeg pregleda.
</p>

<h2>Neobavezno</h2>
<p>
    Mehanizacija je u izborniku, ali dok ne dodate prvi stroj, ništa se ne prikazuje ni ne šalje.
</p>

<h2>Skladište sada može imati više lokacija</h2>
<p>
    Uz to, u <strong>Skladištu</strong> možete dodati više skladišta (npr. „Glavno” i „Ekonomija”) i prenositi robu između njih.
    Kod prskanja i gnojidbe birate iz kojeg skladišta uzimate, a ako ne izaberete, troši se iz glavnog.
</p>
