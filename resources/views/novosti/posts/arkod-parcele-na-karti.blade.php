<p>
    Do sada je ARKOD parcela u AgroLogu bila samo broj i površina koju ste sami upisali. Od danas AgroLog parcelu
    pronađe u javnom ARKOD-u Agencije za plaćanja i pokaže je na satelitskoj karti, tako da odmah vidite je li to
    prava parcela i koliko je velika prema službenoj evidenciji.
</p>

<h2>Nova parcela: upišite broj, potvrdite na karti</h2>
<ol>
    <li>U <em>Parcele &amp; Kulture</em> kliknite <strong>+ Nova parcela</strong> i upišite ARKOD broj.</li>
    <li>Čim izađete iz polja, ispod se pojavi satelitska karta s vašom parcelom (zeleni obrub) i susjednim ARKOD parcelama.</li>
    <li>Uz kartu piše ARKOD ID, <strong>službena površina</strong>, vrsta uporabe (oranica, vinograd, voćnjak…) i lokalni naziv.</li>
    <li>Površina se upiše sama — kliknite <strong>Potvrdi i spremi</strong>.</li>
</ol>
<p>
    Ako je parcela u zoni zaštite izvorišta ili u području Natura 2000, AgroLog vas na to upozori, jer tamo vrijede
    dodatna ograničenja za gnojidbu i zaštitu bilja.
</p>

<h2>Karta uz svaku parcelu</h2>
<p>
    Uz svaki ARKOD broj u popisu parcela nalazi se ikona karte. Klikom se otvori karta te parcele s usporedbom
    površine koju ste upisali i površine prema ARKOD-u. Ako ste upisali više nego što stoji u ARKOD-u, uz parcelu
    piše površina iz ARKOD-a — dobro je to provjeriti prije prijave potpora.
</p>

<h2>Sve vaše parcele na jednoj karti</h2>
<p>
    Na početnoj stranici je karta svih vaših parcela s ARKOD brojevima. Karta se sama približi tako da vidite samo
    svoje parcele, a možete je zumirati i pomicati. Klik na parcelu pokaže kulture koje su na njoj.
    Za parcele unesene prije ove novosti oblik se dohvati automatski pri prvom otvaranju.
</p>

