    <strong>Kupujmo hrvatsko. Podržimo domaće. Uživajmo lokalno. Vjerujmo u naše ljude.</strong>
    Uz evidenciju, AgroLog sada povezuje gospodarstva i kupce: javni popis <a href="{{ route('gospodarstva') }}">Gospodarstva</a>
    i <a href="{{ route('trznica') }}">Tržnica</a> s oglasima za domaće proizvode.
</p>

<h2>Gospodarstva</h2>
<p>
    Svako gospodarstvo može se besplatno predstaviti: opis, slika, što nudi, adresa i točna lokacija na karti s uputama za dolazak.
    Kupci traže po mjestu, županiji i proizvodu, a posebno su označena gospodarstva koja prodaju na kućnom pragu.
    Broj telefona prikazuje se tek na klik, kako ga roboti ne bi skupljali.
</p>

<h2>Tržnica</h2>
<p>
    Gospodarstvo s objavljenom prezentacijom dodaje proizvode s cijenom po kilogramu, litri, komadu ili staklenci, opisom i slikom.
    Uz svaki oglas piše tko prodaje, sav kontakt i gumb <strong>Svi oglasi ovog prodavača</strong>. Kupnju dogovarate izravno s gospodarstvom,
    bez posrednika i bez provizije.
</p>

<h2>Kako se predstaviti</h2>
<ol>
    <li>U <strong>Profilu</strong> uključite <strong>Prezentaciju na AgroLogu</strong>, a novi korisnici to mogu označiti već na registraciji.</li>
    <li>Upišite opis, kontakt i adresu, a na karti označite gdje se nalazite.</li>
    <li>Kad prezentaciju pregledamo i objavimo, pod <strong>Tržnica → Moji proizvodi</strong> dodajte proizvode.</li>
</ol>
<p>Sve je besplatno. Detalji su u <a href="{{ route('docs') }}#trznica">uputama</a>.</p>
