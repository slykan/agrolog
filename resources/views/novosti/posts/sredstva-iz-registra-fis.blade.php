<p>
    Registracijski broj sredstva obvezan je podatak u evidenciji o uporabi sredstava za zaštitu bilja, a od 2027. i u
    Ministarstvovu elektroničkom formatu. Da ga ne morate prepisivati s etikete, AgroLog sada koristi registar sredstava
    iz Fitosanitarnog informacijskog sustava (FIS) Ministarstva poljoprivrede.
</p>

<h2>Kako radi</h2>
<ul>
    <li>Kad u evidenciji prskanja počnete tipkati <strong>trgovački naziv</strong>, AgroLog nudi sredstva koja ste već koristili
        i sva sredstva registrirana u Hrvatskoj — oko 900 sredstava, s registracijskim brojem uz svako.</li>
    <li>Kad odaberete sredstvo, <strong>registracijski broj upiše se sam</strong> (npr. AMISTAR GOLD → UP/I-320-20/14-01/551).
        Promijenite li sredstvo, mijenja se i broj.</li>
    <li>Ako registracija sredstva u FIS-u <strong>nije aktivna</strong>, AgroLog vas upozori da provjerite smije li se još primjenjivati.</li>
    <li>Ako sredstvo nije u registru (npr. naziv je napisan drukčije), dobit ćete napomenu da provjerite naziv s etikete.
        Zapis se i dalje može spremiti.</li>
</ul>

<h2>Uvijek ažurno</h2>
<p>
    Popis sredstava preuzimamo iz javne tražilice FIS-a i osvježavamo ga svaki tjedan, pa se nova sredstva i promjene
    registracija same pojave u AgroLogu.
</p>

<p class="text-sm text-gray-500">
    Registracijski broj i dalje provjerite na etiketi sredstva koje koristite. Službeni podaci o registriranim sredstvima
    nalaze se u <a href="https://fis.mps.hr/trazilicaszb/" target="_blank" rel="noopener">tražilici sredstava za zaštitu bilja</a> na FIS portalu.
</p>
