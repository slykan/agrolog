<p>
    Prije svakog prskanja gledate prognozu: hoće li puhati, hoće li kiša isprati sredstvo, hoće li noću biti mraza.
    Od danas je ta prognoza u AgroLogu, na početnoj stranici, točno za područje vaših parcela.
</p>

<h2>Pet dana unaprijed, iznad karte parcela</h2>
<p>Na početnoj stranici, iznad karte vaših parcela, za danas i sljedeća četiri dana piše:</p>
<ul>
    <li>vrijeme (sunčano, oblačno, kiša, snijeg…) te najviša i najniža temperatura,</li>
    <li>očekivana količina kiše u milimetrima i vjerojatnost kiše,</li>
    <li>najjači vjetar u km/h,</li>
    <li>oznaka je li dan <strong>povoljan za prskanje</strong>.</li>
</ul>
<p>
    Prognoza je za središte karte, dakle za područje gdje su vaše parcele. Pomaknete li kartu na drugo područje,
    prognoza se sama osvježi za to mjesto.
</p>

<h2>Kada je dan povoljan za prskanje</h2>
<p>AgroLog dan označi kao povoljan kad su ispunjeni svi uvjeti:</p>
<table class="tbl">
    <tr><th>Uvjet</th><th>Zašto</th></tr>
    <tr><td>vjetar ispod 15 km/h</td><td>jači vjetar nosi škropivo izvan parcele (zanošenje)</td></tr>
    <tr><td>vjerojatnost kiše ispod 40 %</td><td>kiša nakon tretiranja može isprati sredstvo</td></tr>
    <tr><td>bez mraza</td><td>smrznute biljke slabo primaju sredstvo, a neka mogu oštetiti usjev</td></tr>
    <tr><td>najviša temperatura 5–30 °C</td><td>na hladnom mnoga sredstva slabo djeluju, a na vrućini škropivo brže isparava</td></tr>
</table>
<p>
    Kad dan nije povoljan, piše i razlog — npr. „nije za prskanje: mraz” ili „nije za prskanje: vjetar, kiša”.
</p>
<p class="text-sm text-gray-500">
    Oznaka je pomoć pri planiranju, a ne zamjena za etiketu sredstva: neka sredstva imaju strože uvjete primjene
    (temperatura, vrijeme bez kiše nakon tretiranja, zaštita pčela). Uvijek provjerite etiketu. Prognoza:
    <a href="https://open-meteo.com/" target="_blank" rel="noopener">Open-Meteo</a>.
</p>

