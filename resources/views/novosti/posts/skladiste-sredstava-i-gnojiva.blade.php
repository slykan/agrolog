<p>
    Koliko vam je još ostalo herbicida u kanistru? Ima li dovoljno KAN-a za prihranu? AgroLog sada ima
    <strong>skladište</strong>. Upišete što ste kupili, a potrošnju iz prskanja i gnojidbe AgroLog oduzima sam.
</p>

<h2>Kako radi</h2>
<ul>
    <li><strong>Ulaz:</strong> unesete nabavu, npr. „Roundup, 20 L” ili „KAN 27% N, 2 t”. Cijena i dobavljač nisu obavezni.</li>
    <li><strong>Izlaz:</strong> kad upišete prskanje ili gnojidbu, s tim se artiklom računa <strong>doza po hektaru × površina</strong> i oduzme od stanja. Nema dodatnog unosa.</li>
    <li><strong>Ispravke same od sebe:</strong> ako izmijenite ili obrišete zapis prskanja ili gnojidbe, stanje se samo ispravi.</li>
    <li><strong>Inventura:</strong> ako se izračunato stanje ne slaže sa stvarnim, upišete koliko stvarno imate i AgroLog doda ispravak.</li>
</ul>

<h2>Upozorenja, ali bez blokiranja</h2>
<p>
    U formi prskanja i gnojidbe, ispod naziva sredstva ili gnojiva, piše koliko ga imate na skladištu i koliko će ostati nakon tog zapisa.
    Na početnoj stranici je popis onoga što je pri kraju ili u minusu.
    Unos u evidenciju se <strong>nikad ne blokira</strong>: evidencija ima prednost, a minus samo znači da nabava još nije upisana.
</p>

<h2>Skladište je neobavezno</h2>
<p>
    Za postojeće korisnike skladište je isključeno, pa se ništa ne mijenja dok ga sami ne uključite:
    <strong>Profil → Skladište → Koristim skladište</strong>. Tada se u izborniku pojavi stavka <em>Skladište</em>.
</p>
<p>
    Prati se samo ono što unesete na skladište. Ako želite pratiti samo skupa sredstva, unesite samo njih, a sve ostalo radi kao i do sada.
    Potrošnja se računa od datuma prve nabave tog artikla, pa starija evidencija ne utječe na stanje.
</p>

<h2>Cijena i vrijednost zalihe</h2>
<p>
    Ako uz nabavu upišete cijenu, AgroLog izračuna prosječnu cijenu po litri ili kilogramu i vrijednost onoga što je na skladištu.
    To je temelj za sljedeći korak: trošak zaštite i gnojidbe po parceli i kulturi.
</p>
<p class="text-sm text-gray-500">
    Važno: jedinica na skladištu mora odgovarati dozi u evidenciji. Ako dozu sredstva upisujete u litrama po hektaru, nabavu upišite u litrama,
    a za praškasta sredstva u kilogramima. Naziv u prskanju ili gnojidbi mora biti isti kao na skladištu.
    Najlakše je odabrati ga s ponuđenog popisa.
</p>
