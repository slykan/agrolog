<p>
    Preporuka agronoma često stiže porukom ili pozivom, a onda je netko mora prepisati u evidenciju. U AgroLogu sada ide izravno:
    <strong>agronom pošalje preporuku, gospodarstvo odgovori, a kad posao obavi, zapis je već popunjen.</strong>
</p>

<h2>Za agronome i savjetnike</h2>
<ol>
    <li>Na registraciji ili u profilu označite <strong>Agronom sam ili savjetnik</strong> i pozovite svoje poljoprivrednike.</li>
    <li>Otvorite <strong>Klijenti → Pošalji preporuku</strong> i odaberite prskanje, gnojidbu ili opću poruku.</li>
    <li>Odaberite kulturu. Na popisu su parcele svih klijenata s tom kulturom, a gospodarstva bez nje preporuku ne dobivaju.</li>
    <li>Prije slanja vidite kome ide i, za prskanje, što kaže registar FIS-a.</li>
</ol>
<p>Na istoj stranici pratite stanje svake preporuke i odgovarate na pitanja.</p>

<h2>Za gospodarstva</h2>
<p>
    Obavijest stiže u zvono, a prema vašim postavkama i mailom i pushem. Možete prihvatiti, odbiti ili postaviti pitanje.
    Vi odlučujete što ćete napraviti, a savjetnik ne vidi vaše podatke ako mu niste dali pristup.
</p>

<h2>Evidencija ostaje točna</h2>
<p>
    Prihvaćanje ne upisuje ništa. Kad posao stvarno obavite, kliknite <strong>Napravljeno, unesi u evidenciju</strong>. Otvara se popunjen unos,
    a vi provjerite datum, količinu i ostalo pa spremite. Tako evidencija pokazuje ono što je napravljeno, a ne ono što je bilo preporučeno.
</p>

