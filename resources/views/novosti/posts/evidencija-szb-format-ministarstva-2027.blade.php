<p>
    Ministarstvo poljoprivrede, šumarstva i ribarstva objavilo je kako evidencija o uporabi sredstava za zaštitu
    bilja (SZB) mora izgledati u elektroničkom obliku i dalo profesionalnim korisnicima prijelazno razdoblje.
    AgroLog smo uskladili s tim formatom, pa evidenciju koju vodite kod nas možete izvesti izravno u
    Ministarstvovu tablicu.
</p>

<h2>Što kažu propisi</h2>
<table class="tbl">
    <tr><th>Rok</th><th>Što vrijedi</th></tr>
    <tr><td>od 1. siječnja 2026.</td><td>Profesionalni korisnici vode evidenciju u elektroničkom i strojno čitljivom obliku (Provedbena uredba (EU) 2023/564).</td></tr>
    <tr><td>do 31. prosinca 2026.</td><td>Prijelazno razdoblje: primjene obavljene do tog datuma ne moraju se prenositi u propisani format (Provedbena uredba (EU) 2025/2203).</td></tr>
    <tr><td>od 1. siječnja 2027.</td><td>Svaka primjena mora biti zabilježena u propisanom elektroničkom formatu i dostupna nadležnim tijelima na zahtjev.</td></tr>
</table>
<p>
    Ministarstvo je na FIS portalu objavilo prijedlog tablice <strong>„Evidencija SBZ.xlsx”</strong> s uputom za popunjavanje,
    a najavilo je i vođenje evidencije kroz Fitosanitarni informacijski sustav na portalu ePoljoprivreda (prijava putem NIAS-a).
</p>

<h2>Što tablica traži</h2>
<p>Za svaku pojedinačnu primjenu jednog sredstva upisuje se:</p>
<ul>
    <li>vrsta uporabe (npr. poljoprivredne površine na otvorenom, plastenik, tretiranje sjemena),</li>
    <li>trgovački naziv i registracijski broj sredstva,</li>
    <li>datum i sat početka primjene te primijenjena doza,</li>
    <li>lokacija (ARKOD) i veličina tretirane površine,</li>
    <li>usjev i njegov <strong>EPPO kod</strong>,</li>
    <li><strong>fenofaza rasta usjeva (BBCH)</strong>, kad je relevantna,</li>
    <li><strong>sustav proizvodnje</strong> (ekološka ili neekološka površina).</li>
</ul>

<h2>Što je novo u AgroLogu</h2>
<ul>
    <li><strong>EPPO kod uz svaku kulturu.</strong> Kod se sam prepozna iz naziva (npr. Pšenica → TRZAX, Kukuruz → ZEAMX).
        Možete ga i odabrati s Ministarstvova popisa od 1.400 usjeva. Kultura bez prepoznatog koda označena je u
        <em>Parcele &amp; Kulture</em> natpisom „bez EPPO koda”.</li>
    <li><strong>Fenofaza (BBCH)</strong> pri unosu prskanja, s prijedlozima za odabranu kulturu iz Ministarstvova popisa.</li>
    <li><strong>Vrsta uporabe i sustav proizvodnje</strong> — zadano „na otvorenom” i „neekološka”, a novi unos preuzima ono što ste koristili zadnji put.</li>
    <li><strong>Izvoz „Excel (Ministarstvo)”</strong> u evidenciji prskanja: preuzimate Ministarstvov predložak već popunjen vašim zapisima,
        s vašim imenom i OIB-om u zaglavlju te svim stupcima redom kako ih tablica traži.</li>
    <li>I dosadašnji <strong>CSV izvoz</strong> sada sadrži EPPO kod, fenofazu, vrstu uporabe i sustav proizvodnje.</li>
</ul>
<p>
    Postojećim zapisima postavili smo vrstu uporabe „na otvorenom” i sustav „neekološka”, a kulturama EPPO kod gdje se mogao
    prepoznati iz naziva. Ako imate ekološku proizvodnju ili plastenike, otvorite te zapise i promijenite ih.
</p>

<h2>Što trebate napraviti</h2>
<ol>
    <li>U <em>Parcele &amp; Kulture</em> provjerite imaju li sve aktivne kulture EPPO kod.</li>
    <li>Kod novih prskanja upišite fenofazu (BBCH) kad je važna za sredstvo i kulturu.</li>
    <li>Prije kontrole ili na kraju sezone preuzmite <strong>Excel (Ministarstvo)</strong> i spremite ga uz ostalu dokumentaciju.</li>
</ol>
