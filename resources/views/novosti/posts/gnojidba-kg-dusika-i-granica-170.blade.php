<h2>Odaberite gnojivo, AgroLog izračuna dušik</h2>
<ul>
    <li>U polju <strong>Tip gnojiva</strong> nudi se popis uobičajenih gnojiva: KAN, UREA, AN, AS, UAN, NPK 15-15-15, 7-20-30,
        8-26-26, 10-20-30, PK, MAP, DAP, superfosfat, kalijev klorid i sulfat te stajski gnoj, gnojovka i gnojnica.</li>
    <li>Odabirom se upišu <strong>udjeli N, P₂O₅ i K₂O</strong>, a iz količine se izračuna <strong>kg N po hektaru</strong>
        — npr. 300 kg/ha KAN-a (27 % N) = 81 kg N/ha.</li>
    <li>Za gnojivo kojeg nema na popisu upišite udjele s deklaracije, a prepoznaju se i zapisi poput „NPK 7-20-30” ili „7:20:30”.</li>
    <li>Stari zapisi dobili su sastav i izračun automatski, gdje se naziv gnojiva mogao prepoznati.</li>
</ul>

