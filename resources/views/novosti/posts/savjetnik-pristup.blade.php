<p>
    Evidenciju često ne vodi samo gospodarstvo: tu su savjetodavna služba, agronom ili zadruga. AgroLog sada omogućuje da
    <strong>pozovete svog savjetnika</strong> — on vidi vašu evidenciju i, ako mu dopustite, vodi je umjesto vas.
</p>

<h2>Kako pozvati savjetnika</h2>
<ol>
    <li>Otvorite <strong>Profil → Pristup savjetniku</strong>.</li>
    <li>Upišite e-mail savjetnika i odaberite prava: <strong>samo pregled</strong> ili <strong>pregled i unos</strong>.</li>
    <li>Savjetnik dobije mail s poveznicom, prijavi se ili besplatno registrira i prihvati poziv. Vi dobijete potvrdu mailom.</li>
</ol>

<h2>Uvijek znate tko je što mijenjao</h2>
<p>
    Svaka izmjena koju savjetnik napravi bilježi se u <strong>povijest izmjena</strong> u vašem profilu — tko, kada i što.
    Prava možete promijeniti ili pristup ukinuti jednim klikom. Savjetnik ne vidi vaš profil ni lozinku.
</p>

<h2>Za savjetnike: svi klijenti na jednom mjestu</h2>
<p>
    Savjetnik pod <strong>Klijenti</strong> vidi sva gospodarstva koja su mu dala pristup: površinu, zadnji unos i što traži pažnju —
    zapise za dopuniti za evidenciju 2027., istekle rokove, karence i skladište u minusu. Klikom na <strong>Otvori</strong>
    radi u gospodarstvu klijenta (parcele, prskanje, gnojidba, ispis i Excel za Ministarstvo), a gumbom
    <strong>Natrag na svoje</strong> vraća se u svoje.
</p>
