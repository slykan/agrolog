<p>
    Koliko vas stoji hektar pšenice, a koliko suncokreta? AgroLog sada ima stranicu <strong>Troškovi</strong>. Iz cijena nabave na skladištu
    i iz evidencije prskanja i gnojidbe sam izračuna trošak zaštite bilja i gnojidbe po parceli i po hektaru.
</p>

<h2>Što pokazuje</h2>
<ul>
    <li><strong>Nabava po mjesecima:</strong> koliko ste potrošili na sredstva za zaštitu bilja, a koliko na gnojiva. Prijeđite mišem preko stupca za iznose.</li>
    <li><strong>Nabava po vrsti:</strong> udio zaštite bilja i gnojiva u ukupnoj nabavi.</li>
    <li><strong>Trošak po parceli i kulturi:</strong> utrošena sredstva i gnojiva (doza × površina) po prosječnoj nabavnoj cijeni, s iznosom po hektaru.</li>
    <li><strong>Utrošak po sredstvu i gnojivu:</strong> količina i iznos za svako sredstvo i gnojivo.</li>
</ul>
<p>Razdoblje birate jednim klikom: ova godina, prošla, zadnjih 12 mjeseci ili od–do.</p>

<h2>Odakle brojke</h2>
<p>
    Troškovi se računaju iz <strong>skladišta</strong>: uz nabavu upišite i „Cijena ukupno (€)”. Iz toga AgroLog računa prosječnu cijenu po litri ili kilogramu,
    a svaki zapis prskanja ili gnojidbe s tim sredstvom ili gnojivom dobije svoj trošak. Prijenosi između skladišta i inventure ne broje se kao nabava.
    Ako neko sredstvo nema cijenu, AgroLog to napiše, pa je možete dopuniti.
</p>
<p class="text-sm text-gray-500">Na početnoj stranici je i novi Pregled gospodarstva s aktivnostima po mjesecima i usporedbom s prošlom godinom.</p>
