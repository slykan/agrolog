<p>
    Svaki profesionalni korisnik sredstava za zaštitu bilja — poljoprivrednik koji prska svoje ili tuđe
    površine — dužan je voditi evidenciju o svakoj primjeni. Ta obveza postoji godinama, ali se mijenja
    <strong>oblik</strong>: umjesto bilježnice ili papirnatog evidencijskog lista evidencija se mora voditi
    <strong>elektronički i u strojno čitljivom obliku</strong>.
</p>

<h2>Odakle obveza</h2>
<ul>
    <li><strong>Uredba (EZ) br. 1107/2009</strong>, članak 67. — profesionalni korisnici vode evidenciju o sredstvima za zaštitu bilja koja upotrebljavaju.</li>
    <li><strong>Provedbena uredba Komisije (EU) 2023/564</strong> — propisuje sadržaj i format te evidencije, uključujući elektronički i strojno čitljiv oblik.</li>
    <li><strong>Zakon o održivoj uporabi pesticida</strong> (NN 46/2022) — nacionalni okvir za profesionalne korisnike.</li>
</ul>

<h2>Rokovi</h2>
