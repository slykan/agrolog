<p>
    Ministarstvo poljoprivrede najavilo je da će elektroničko vođenje evidencije biti omogućeno i kroz
    Fitosanitarni informacijski sustav (FIS) na portalu ePoljoprivreda. Do tada se evidencija može voditi u
    drugim elektroničkim alatima koji omogućuju strojno čitljiv izvoz podataka.
</p>

<h2>Što evidencija mora sadržavati</h2>
<p>Za <strong>svaku pojedinačnu primjenu</strong> evidencija mora biti točna, potpuna i ažurna, a uključuje najmanje:</p>
<ul>
    <li>puni <strong>trgovački naziv</strong> sredstva, kako piše na etiketi,</li>
    <li><strong>registracijski broj</strong> (broj rješenja o registraciji) sredstva,</li>
    <li><strong>datum</strong> (i po potrebi vrijeme) primjene,</li>
    <li>primijenjenu <strong>dozu</strong>,</li>
    <li><strong>površinu</strong> i lokaciju — parcelu — na kojoj je sredstvo primijenjeno,</li>
    <li><strong>kulturu</strong> na kojoj je sredstvo primijenjeno.</li>
</ul>
<div class="box-note">
    Najlakše je evidenciju voditi po <strong>ARKOD parcelama</strong>: površina i identifikacija parcele tada su uvijek
    iste kao u zahtjevu za potporu, pa ih ne treba svaki put iznova upisivati.
</div>

<h2>Što se smatra „elektroničkim i strojno čitljivim"</h2>
<p>
    Fotografija ili sken papirnatog lista nije strojno čitljiv zapis. Strojno čitljivi su podaci koje računalo može
    izravno obraditi — npr. zapisi u aplikaciji ili tablici koji se mogu izvesti kao CSV, Excel ili XML. Konačni
    propisani format objavit će nadležno ministarstvo.
</p>

<h2>Koliko dugo čuvati</h2>
<p>
    Uredba 1107/2009 propisuje čuvanje evidencije najmanje <strong>tri godine</strong>. Savjetodavna služba u svojim
    uputama navodi i rok od <strong>pet godina</strong> — za svaki slučaj, čuvaj evidenciju pet godina.
</p>

<h2>Kako to rješava AgroLog</h2>
<ul>
    <li>Prskanja se upisuju po ARKOD parcelama, s nazivom i <strong>registracijskim brojem</strong> sredstva, dozom, kulturom, površinom, datumom i vremenom.</li>
    <li>Registracijski broj se predlaže sam kad ponovno koristiš isto sredstvo.</li>
    <li>Cijela evidencija izvozi se jednim klikom u <strong>CSV</strong> — strojno čitljiv oblik koji se otvara u Excelu.</li>
    <li>Za kontrolu na terenu evidencija se može i ispisati.</li>
</ul>
