<p>
    Prskalica i atomizer koji se koriste za primjenu sredstava za zaštitu bilja moraju redovito na
    <strong>pregled u ovlaštenu ispitnu stanicu</strong>. Stroj koji nije prošao pregled ne smije se koristiti.
    Ovdje je sve što trebaš znati: koliko često, koji strojevi, kako se pripremiti i što se provjerava.
</p>

<h2>Koliko često</h2>
<table class="tbl">
    <tr><th>Stroj</th><th>Pregled</th></tr>
    <tr><td>Stroj u uporabi</td><td>najmanje jednom u <strong>tri godine</strong> od zadnjeg pregleda</td></tr>
    <tr><td>Novi stroj</td><td>prvi pregled u roku od <strong>pet godina</strong> od kupnje, zatim svake tri godine</td></tr>
</table>
<p>
    Novi stroj treba prijaviti ovlaštenoj ispitnoj stanici prije prve uporabe, a najkasnije u roku od četiri
    mjeseca od kupnje. Ako je stroj u skladu s propisima i normama koje su vrijedile kad ga je distributer
    stavio na tržište, dobiva oznaku i bez pregleda. Stroj kupljen prije više od šest mjeseci smatra se
    rabljenim i mora na pregled.
</p>

<h2>Koji strojevi ne moraju na pregled</h2>
<p>
    Izuzeti su ručni strojevi i leđne prskalice — ručne, baterijske i motorne — te leđni motorni raspršivači.
    Vlasnici <strong>leđnih motornih</strong> prskalica i raspršivača ipak ih moraju prijaviti ovlaštenoj ispitnoj
    stanici radi upisa u registar. Sve ostale prskalice i atomizeri (nošeni, vučeni, samohodni) podliježu
    redovitom pregledu.
</p>

<h2>Kako se pripremiti</h2>
<ol>
    <li>Dogovori termin s ovlaštenom ispitnom stanicom — popis je na stranicama Ministarstva poljoprivrede.</li>
    <li>Stroj dovezi <strong>čist</strong>, izvana i iznutra, bez ostataka škropiva.</li>
    <li>Spremnik napuni <strong>čistom vodom</strong> do najmanje polovice volumena (za strojeve do 600 litara do dvije trećine).</li>
    <li>Ponesi osobnu iskaznicu ili dokument s OIB-om.</li>
    <li>Prije pregleda sam provjeri očito: curenja, oštećena crijeva, zaštitu kardanskog vratila, manometar i sapnice.</li>
</ol>

<h2>Što se provjerava</h2>
<p>
    Pregled se obavlja prema normama serije <strong>HRN EN ISO 16122</strong>. Prvo se gleda čistoća i očiti
    sigurnosni nedostaci, a zatim tehnička ispravnost:
</p>
<ul>
    <li>zaštita kardanskog vratila i pokretnih dijelova,</li>
    <li>kapacitet i nepropusnost crpke, miješanje u spremniku,</li>
    <li>spremnik, poklopac, sita i filtri,</li>
    <li>mjerenje i regulacija tlaka (manometar), crijeva i vodovi,</li>
    <li>stabilnost krila, protok svake sapnice i ravnomjernost raspodjele,</li>
    <li>kod atomizera i ventilator.</li>
</ul>
<p>
    Stroj koji prođe dobiva zapisnik i zelenu naljepnicu s natpisom <strong>„PREGLEDANO"</strong>, koja se lijepi na
    mjesto gdje se najmanje oštećuje. Zapisnik čuvaj do idućeg pregleda.
</p>

<h2>Obveze vlasnika između pregleda</h2>
<ul>
    <li>Redovito umjeravaj (kalibriraj), održavaj i čisti stroj — vidi vodič <a href="{{ route('vodic', 'kalibracija-prskalice-korak-po-korak') }}">kalibracija prskalice korak po korak</a>.</li>
    <li>Izgubljenu ili oštećenu naljepnicu zamijeni.</li>
    <li>Promjenu vlasništva prijavi ispitnoj stanici pisano u roku od 30 dana.</li>
    <li>Stroj koji više ne koristiš, ili mu je naljepnica istekla prije više od 30 dana, prijavi radi odjave.</li>
</ul>

<h2>Zašto se isplati</h2>
<p>
    Osim što je obvezan, pregled često otkrije istrošene sapnice koje izbacuju i 10–15 % više škropiva od
    nazivnog protoka, ili neravnomjernu raspodjelu po krilu. To znači previše sredstva na jednom dijelu parcele,
    premalo na drugom i bačen novac. Ispravna prskalica, uz dobru kalibraciju, plaća pregled već kroz
    nekoliko tretiranja.
</p>

