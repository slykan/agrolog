<p>
    Preporuke gnojidbe — iz analize tla, od savjetodavca ili iz literature — gotovo uvijek su izražene u
    <strong>kilogramima čistog hraniva po hektaru</strong>: npr. 120 kg N/ha za kukuruz. U trgovini se, međutim,
    kupuju vreće KAN-a, UREE ili NPK gnojiva. Kako jedno pretvoriti u drugo?
</p>

<h2>Postotak hraniva u gnojivu</h2>
<table class="tbl">
    <tr><th>Gnojivo</th><th>Sadržaj hraniva</th><th class="num">kg hraniva u vreći od 50 kg</th></tr>
    <tr><td>KAN</td><td>27 % N</td><td class="num">13,5 kg N</td></tr>
    <tr><td>UREA</td><td>46 % N</td><td class="num">23 kg N</td></tr>
    <tr><td>NPK 15-15-15</td><td>15 % N, 15 % P₂O₅, 15 % K₂O</td><td class="num">po 7,5 kg</td></tr>
    <tr><td>NPK 7-20-30</td><td>7 % N, 20 % P₂O₅, 30 % K₂O</td><td class="num">3,5 / 10 / 15 kg</td></tr>
</table>
<p>Fosfor i kalij iskazuju se kao oksidi (P₂O₅ i K₂O), i preporuke su u istim jedinicama.</p>

<h2>Formula</h2>
<p><strong>kg gnojiva/ha = kg hraniva/ha × 100 ÷ % hraniva u gnojivu</strong></p>
<h3>Primjer: 120 kg N/ha</h3>
<ul>
    <li>KAN: 120 × 100 ÷ 27 = <strong>444 kg/ha</strong> (oko 9 vreća od 50 kg po hektaru)</li>
    <li>UREA: 120 × 100 ÷ 46 = <strong>261 kg/ha</strong> (oko 5,2 vreće)</li>
</ul>
<p>Isto računa <a href="{{ route('alat', 'kalkulator-gnojiva') }}">kalkulator gnojiva</a>, uz broj vreća za cijelu površinu.</p>

<h2>NPK gnojiva: računaj prema glavnom hranivu</h2>
<p>
    Kod složenih gnojiva odaberi hranivo prema kojem računaš (najčešće P ili K u osnovnoj gnojidbi), izračunaj
    količinu gnojiva, pa provjeri koliko si time unio ostalih hraniva. Ako trebaš 60 kg P₂O₅/ha s NPK 7-20-30, to je
    300 kg/ha gnojiva — a uz to i 21 kg N i 90 kg K₂O. Dušik koji nedostaje dodaje se prihranom KAN-om ili UREOM.
</p>

<h2>Prihrana u više obroka</h2>
<p>
    Dušik se lako ispire, pa se ukupna količina obično dijeli: dio u osnovnoj gnojidbi ili pred sjetvu, ostatak u
    jednoj ili dvije prihrane u vrijeme najveće potrebe biljke. Tako je iskorištenje bolje, a gubici u podzemne vode manji.
</p>

<h2>Ranjiva područja i nitrati</h2>
<p>
    Na <strong>područjima ranjivim na nitrate</strong> gospodarstva moraju poštivati mjere Akcijskog programa zaštite
    voda od onečišćenja uzrokovanog nitratima poljoprivrednog podrijetla — trenutno IV. akcijskog programa
    (NN 95/2025, primjena od 1. srpnja 2025.). Među njima su:
</p>
<ul>
    <li>vođenje <strong>evidencije gnojidbe</strong> na propisanom obrascu,</li>
    <li>ograničenje unosa dušika iz stajskog gnoja (prema Nitratnoj direktivi EU najviše 170 kg N/ha godišnje),</li>
    <li>razdoblja i uvjeti u kojima je gnojidba zabranjena (npr. na zamrznutom ili vodom zasićenom tlu i u određenim dijelovima godine).</li>
</ul>
<p>Izvan ranjivih područja te mjere su preporuka. Točne zabrane i rokove provjeri u akcijskom programu ili kod savjetodavne službe.</p>
