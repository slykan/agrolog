<p>
    Kalibracija (umjeravanje) prskalice znači utvrditi koliko litara škropiva tvoja prskalica stvarno izbaci
    po hektaru. Bez toga je svaka doza s etikete samo pretpostavka. Postupak traje pola sata, treba ti mjerna
    posuda, štoperica i metar — a jednom godišnje i nakon svake promjene sapnica isplati se ponoviti.
</p>

<h2>Formula</h2>
<p>
    Utrošak vode po hektaru ovisi o tri stvari: protoku jedne sapnice, brzini vožnje i razmaku između sapnica.
</p>
<div class="box-note">
    <strong>utrošak (l/ha) = protok sapnice (l/min) × 600 ÷ (brzina (km/h) × razmak sapnica (m))</strong>
</div>
<p>
    Broj 600 dolazi iz pretvorbe jedinica (minute u sate, metre u hektare). Formula vrijedi za ratarske
    prskalice s krilom; kod atomizera vidi odjeljak niže.
</p>

<h2>Korak 1: izmjeri stvarnu brzinu</h2>
<p>
    Na parceli (ne na asfaltu — kotači proklizavaju drukčije) označi 100 m. Vozi u radnoj brzini i stupnju
    prijenosa, s napola punim spremnikom, i izmjeri vrijeme u sekundama.
</p>
<p><strong>brzina (km/h) = 360 ÷ vrijeme (s)</strong></p>
<p>Primjer: 100 m za 45 s → 360 ÷ 45 = <strong>8 km/h</strong>.</p>

<h2>Korak 2: izmjeri protok sapnica</h2>
<ol>
    <li>Napuni spremnik čistom vodom i postavi radni tlak.</li>
    <li>Ispod sapnice drži mjernu posudu točno <strong>jednu minutu</strong>.</li>
    <li>Ponovi na barem 4–5 sapnica duž krila (idealno na svima) i zapiši rezultate.</li>
    <li>Izračunaj prosjek. Sapnicu koja odstupa više od oko 10 % od prosjeka ili od nazivnog protoka iz tablice proizvođača očisti ili zamijeni.</li>
</ol>

<h2>Korak 3: izračunaj utrošak</h2>
<p>
    Prosječni protok 1,6 l/min, brzina 8 km/h, razmak sapnica 0,5 m:
</p>
<p><strong>1,6 × 600 ÷ (8 × 0,5) = 960 ÷ 4 = 240 l/ha</strong></p>
<p>
    Ako etiketa traži 200–300 l/ha, prskalica je u rasponu. Ako trebaš više vode, smanji brzinu ili povećaj
    tlak (umjereno) ili ugradi veće sapnice; za manje vode obrnuto. Promjena tlaka ima mali učinak — za
    dvostruki protok tlak bi trebao porasti četiri puta — pa je za veće promjene bolje promijeniti sapnice.
</p>

<h2>Korak 4: provjera u praksi</h2>
<p>
    Napuni spremnik do oznake, poprskaj poznatu površinu (npr. 0,5 ha) i dolij do iste oznake. Količina koju
    si dolio, podijeljena s površinom, mora biti blizu izračunatog utroška. Velika razlika znači da nešto ne
    štima — brzinomjer, manometar ili začepljena sita.
</p>

<h2>Atomizeri u voćnjaku i vinogradu</h2>
<p>
    Kod atomizera se umjesto razmaka sapnica uzima <strong>razmak redova</strong>, a protok je zbroj svih otvorenih
    sapnica:
</p>
<p><strong>utrošak (l/ha) = ukupni protok svih sapnica (l/min) × 600 ÷ (brzina (km/h) × razmak redova (m))</strong></p>
<p>
    Primjer: 10 sapnica po 1,2 l/min = 12 l/min, brzina 6 km/h, redovi na 3,5 m → 12 × 600 ÷ 21 ≈
    <strong>343 l/ha</strong>. Zatvori sapnice koje prskaju iznad krošnje — to je čisti gubitak i zanošenje.
</p>

