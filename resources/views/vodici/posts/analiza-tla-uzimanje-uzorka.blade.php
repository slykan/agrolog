<p>
    Gnojidba „po osjećaju" često znači previše fosfora i kalija na jednoj parceli i premalo na drugoj. Analiza tla
    pokaže što tlo već ima, pa gnojiš samo ono što nedostaje. Laboratorij je točan koliko i uzorak koji mu doneseš —
    zato je najvažnije dobro uzeti uzorak.
</p>

<h2>Kada uzeti uzorak</h2>
<ul>
    <li>Najbolje <strong>nakon žetve ili berbe</strong>, a prije osnovne gnojidbe — u ratarstvu najčešće ljeto i jesen.</li>
    <li>Ne odmah nakon gnojidbe ili kalcizacije — pričekaj nekoliko mjeseci.</li>
    <li>Tlo ne smije biti ni presuho ni raskvašeno.</li>
    <li>Ponavljaj svakih nekoliko godina na istoj parceli, u isto doba godine, da rezultate možeš uspoređivati.</li>
</ul>

<h2>Na kojoj dubini</h2>
<table class="tbl">
    <tr><th>Proizvodnja</th><th>Dubina</th></tr>
    <tr><td>Ratarske kulture, povrće, cvijeće</td><td>0–30 cm</td></tr>
    <tr><td>Voćnjaci, vinogradi, maslinici</td><td>0–30 cm i 30–60 cm (dva odvojena uzorka)</td></tr>
    <tr><td>Mineralni dušik (Nmin) u proljeće</td><td>i dublje, do 60–90 cm</td></tr>
</table>

<h2>Kako uzeti prosječni uzorak</h2>
<ol>
    <li><strong>Podijeli parcelu</strong> na ujednačene dijelove. Jedan prosječni uzorak uzima se s ujednačene površine — preporuke se kreću od oko 2 do 5 ha. Dio parcele koji se razlikuje (vlažnije mjesto, drukčija boja tla, nagib, slabiji rast) uzorkuj posebno.</li>
    <li><strong>Hodaj cik-cak</strong> po cijeloj površini i sondom ili ašovom uzmi <strong>20–25 pojedinačnih uzoraka</strong> s iste dubine.</li>
    <li><strong>Izbjegavaj</strong> rubove parcele, uvratine, mjesta gdje je stajao gnoj ili vapno, krtičnjake i tragove kotača.</li>
    <li>Sve pojedinačne uzorke s iste dubine stavi u <strong>čistu kantu</strong> i dobro izmiješaj.</li>
    <li>Iz smjese uzmi <strong>0,5–1 kg</strong> tla u čistu vrećicu.</li>
    <li>Označi vrećicu: ime, parcela (ARKOD), dubina, datum, kultura koju planiraš sijati.</li>
</ol>
<div class="box-note">
    Ako ašovom kopaš, iskopaj jamu, s ravne stijenke odreži ploškom tanku krišku od površine do zadane dubine i
    uzmi srednji dio. Tako svaki poduzorak ima jednako tla iz svih slojeva.
</div>

<h2>Što pokazuje osnovna analiza</h2>
<ul>
    <li><strong>pH (reakcija tla)</strong> — kisela tla (niski pH) slabije koriste hraniva; rješenje je kalcizacija.</li>
    <li><strong>Humus</strong> — organska tvar; utječe na strukturu tla, vodu i dušik.</li>
    <li><strong>Fosfor (P₂O₅) i kalij (K₂O)</strong> — biljci pristupačne količine, obično u mg/100 g tla, s ocjenom opskrbljenosti (slaba, dobra, visoka).</li>
    <li>Po potrebi: karbonati, mikroelementi, mineralni dušik, tekstura tla.</li>
</ul>

<h2>Od nalaza do gnojidbe</h2>
<p>
    Laboratorij ili savjetodavna služba uz nalaz često daju i <strong>preporuku gnojidbe</strong> u kg hraniva po hektaru
    (N, P₂O₅, K₂O) za kulturu koju planiraš. Na slabo opskrbljenim tlima preporuka je veća, na visoko opskrbljenima
    fosfor i kalij se mogu smanjiti ili preskočiti — tu je najveća ušteda.
</p>
<p>
    Preporuku u kilogramima hraniva pretvori u kilograme gnojiva u <a href="{{ route('alat', 'kalkulator-gnojiva') }}">kalkulatoru gnojiva</a>,
    a gnojidbu zapiši u evidenciju — vidi <a href="{{ route('vodic', 'evidencija-gnojidbe-sto-upisati') }}">evidencija gnojidbe: što upisati</a>.
    Na ranjivim područjima pazi i na <a href="{{ route('vodic', 'nitrati-ranjiva-podrucja-zabrana-gnojidbe') }}">ograničenja gnojidbe dušikom</a>.
</p>

