<h2>Voćnjaci i vinogradi</h2>
<p>
    U trajnim nasadima doza se ponekad navodi kao <strong>koncentracija</strong> (npr. 0,2 %, odnosno 200 ml na 100 l
    vode) uz preporučeni utrošak vode po hektaru. Tada je: sredstvo po spremniku = volumen spremnika × koncentracija.
    Za spremnik od 1.000 l i 0,2 % to je 2 l sredstva. Uvijek provjeri da ukupna količina po hektaru ne prelazi
    najveću dopuštenu dozu s etikete.
</p>

<h2>Česte greške</h2>
<ul>
    <li><strong>Doza „po spremniku" iz navike</strong> — kad se promijeni sapnica ili brzina, mijenja se i površina po spremniku.</li>
    <li><strong>Miješanje l/ha i % koncentracije</strong> — to su dva različita načina zadavanja doze.</li>
    <li><strong>Nekalibrirana prskalica</strong> — istrošene sapnice mogu izbacivati i 10–15 % više nego nove.</li>
</ul>
