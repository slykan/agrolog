<p>
    Na etiketi sredstva doza je najčešće izražena po hektaru (npr. 1,5 l/ha), a prskalica ima spremnik od, recimo,
    600 litara. Koliko sredstva ide u jedan spremnik? Odgovor ovisi o tome koliko vode prskalica izbaci po hektaru.
</p>

<h2>1. Utrošak vode po hektaru</h2>
<p>
    Utrošak vode (l/ha) ovisi o sapnicama, tlaku i brzini vožnje. Etiketa obično daje preporučeni raspon (npr.
    200–400 l/ha za ratarske kulture), a stvarni utrošak tvoje prskalice dobiješ <strong>kalibracijom</strong>:
    izmjeri koliko vode prskalica potroši na poznatoj površini pri radnoj brzini i tlaku.
</p>

<h2>2. Koliko hektara pokriva jedan spremnik</h2>
<p><strong>površina po spremniku (ha) = volumen spremnika (l) ÷ utrošak vode (l/ha)</strong></p>
<p>Spremnik 600 l, utrošak 300 l/ha → jedan spremnik pokriva 2 ha.</p>

<h2>3. Koliko sredstva ide u spremnik</h2>
<p><strong>sredstvo po spremniku = doza (l/ha ili kg/ha) × površina po spremniku (ha)</strong></p>
<p>Doza 1,5 l/ha × 2 ha = <strong>3 l sredstva</strong> u pun spremnik od 600 l.</p>

<h2>4. Zadnje, nepuno punjenje</h2>
<p>
    Ako tretiraš 5 ha, trebaš dva puna spremnika (4 ha) i zadnje punjenje za 1 ha: 300 l vode i 1,5 l sredstva.
    Ne miješaj puni spremnik „za svaki slučaj" — višak škropiva je problem za zbrinjavanje i za okoliš.
</p>
