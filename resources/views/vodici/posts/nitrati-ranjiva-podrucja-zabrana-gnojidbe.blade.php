<p>
    Dušik iz gnojiva koji biljke ne iskoriste ispire se u podzemne vode i vodotoke. Zato postoji
    <strong>Akcijski program zaštite voda od onečišćenja uzrokovanog nitratima poljoprivrednog podrijetla</strong> —
    skup pravila o tome kada, koliko i gdje se smije gnojiti. Aktualna verzija objavljena je u Narodnim novinama
    95/2025. Evo najvažnijeg.
</p>

<h2>Na koga se odnosi</h2>
<p>
    Program je <strong>obvezan</strong> za poljoprivredna gospodarstva koja imaju zemljište ili objekte na
    <strong>ranjivim područjima</strong>, određenima posebnom odlukom (s kartom i popisom općina). Izvan ranjivih
    područja iste mjere vrijede kao <strong>preporuka</strong> dobre poljoprivredne prakse. Provjeri u kojoj je zoni
    tvoje gospodarstvo — popis je u Odluci o određivanju ranjivih područja, a zna ga i savjetodavna služba.
</p>

<h2>Razdoblja zabrane gnojidbe</h2>
<table class="tbl">
    <tr><th>Što</th><th>Zabranjeno</th></tr>
    <tr><td>Gnojnica i gnojovka, sve poljoprivredne površine bez obzira na pokrov</td><td><strong>15. prosinca – 15. ožujka</strong></td></tr>
    <tr><td>Gnojnica i gnojovka razbacane po površini <em>bez unošenja u tlo</em></td><td><strong>1. svibnja – 1. rujna</strong></td></tr>
</table>
<p>
    Neovisno o datumu, gnojidba <strong>bilo kojim</strong> gnojidbenim proizvodom zabranjena je na tlu:
</p>
<ul>
    <li>zasićenom vodom ili poplavljenom,</li>
    <li>prekrivenom snijegom,</li>
    <li>smrznutom.</li>
</ul>

<h2>Udaljenost od voda i nagibi</h2>
<ul>
    <li>Najmanje <strong>20 m</strong> od vanjskog ruba stajaćice (jezera, ribnjaka).</li>
    <li>Najmanje <strong>3 m</strong> od ruba korita vodotoka širokog 5 m ili više.</li>
    <li>Na nagibu većem od <strong>10 %</strong> ne gnoji se na manje od <strong>10 m</strong> od ruba korita vodotoka.</li>
</ul>

