<h2>Koliko dušika ima stajski gnoj</h2>
<p>Program daje okvirni sadržaj dušika po vrsti gnoja:</p>
<table class="tbl">
    <tr><th>Gnoj</th><th class="num">% N</th><th class="num">kg N u 10 t</th></tr>
    <tr><td>Goveđi stajski gnoj</td><td class="num">0,5</td><td class="num">50</td></tr>
    <tr><td>Konjski</td><td class="num">0,6</td><td class="num">60</td></tr>
    <tr><td>Ovčji</td><td class="num">0,8</td><td class="num">80</td></tr>
    <tr><td>Svinjski</td><td class="num">0,6</td><td class="num">60</td></tr>
    <tr><td>Peradarski</td><td class="num">1,5</td><td class="num">150</td></tr>
