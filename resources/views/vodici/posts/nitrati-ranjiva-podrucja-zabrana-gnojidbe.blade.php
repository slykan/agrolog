</table>
<p>
    Primjer: 30 t goveđeg gnoja po hektaru = 30.000 kg × 0,5 % = <strong>150 kg N/ha</strong> — ispod granice od 170 kg.
    Ako laboratorijska analiza pokaže manji sadržaj hraniva, smije se unijeti i više gnoja.
</p>

<h2>Skladištenje stajskog gnoja</h2>
<p>
    Spremnici (gnojišta, jame za gnojnicu i gnojovku) moraju primiti gnoj nastao u razdoblju od
    <strong>šest mjeseci</strong>. Višak gnoja koji se predaje drugome mora biti pisano dokumentiran.
</p>

