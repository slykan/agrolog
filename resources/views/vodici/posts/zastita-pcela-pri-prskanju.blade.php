<p>
    Pčele oprašuju velik dio voća, povrća i uljarica — a trovanje pčela jedan je od najvidljivijih problema
    nepravilnog prskanja. Zakon o održivoj uporabi pesticida ima posebna pravila za zaštitu pčela i
    oprašivača. Ovo su pravila i praktični savjeti koje treba znati prije svakog tretiranja.
</p>

<h2>Osnovno pravilo: nema prskanja opasnim sredstvima u cvatnji</h2>
<div class="box-note">
    U vrijeme cvatnje poljoprivrednih kultura <strong>zabranjena je primjena pesticida opasnih za pčele</strong>.
</div>
<p>
    Je li sredstvo opasno za pčele piše na <strong>etiketi</strong> — potraži upozorenja i oznake vezane uz pčele,
    npr. zabranu primjene u cvatnji ili za vrijeme leta pčela. Ista djelatna tvar može biti u više sredstava, a
    svako ima svoje uvjete, pa uvijek čitaj etiketu točno tog proizvoda.
</p>

<h2>Obavijest pčelarima</h2>
<p>
    Prije svakog tretiranja sredstvom opasnim za pčele treba obavijestiti <strong>Hrvatski pčelarski savez</strong> i
    nadležne pčelarske udruge. Dobra praksa je obavijest dati na vrijeme — najmanje dan-dva unaprijed — i navesti:
</p>
<ul>
    <li>kulturu i lokaciju (parcelu, naselje),</li>
    <li>datum i predviđeno vrijeme tretiranja,</li>
    <li>trgovački naziv sredstva.</li>
</ul>
<p>
    Pčelari tada mogu zatvoriti ili premjestiti košnice. Ako se termin pomakne, ponovno obavijesti.
</p>

<h2>Cvatući pokrov u voćnjacima i vinogradima</h2>
<p>
    I kad sama kultura ne cvate, pčele dolaze na <strong>cvatući korov i pokrov</strong> između redova (maslačak,
    djetelina, facelija…). Prije tretiranja sredstvom opasnim za pčele u trajnim nasadima pokrov treba
    <strong>pokositi</strong> ili na drugi način spriječiti da dođe u dodir sa škropivom.
</p>

<h2>Praktični savjeti</h2>
<ul>
    <li><strong>Vrijeme dana</strong> — ako tretiraš izvan cvatnje, a u blizini ima pčela, prskaj kasno navečer kad pčele ne lete. To nije zamjena za zabranu u cvatnji.</li>
    <li><strong>Vjetar</strong> — ne prskaj po vjetru; zanošenje nosi škropivo na susjedne cvatuće kulture, živice i košnice.</li>
    <li><strong>Izbor sredstva</strong> — gdje postoji izbor, odaberi sredstvo koje nije opasno za pčele ili ima kraće djelovanje.</li>
    <li><strong>Integrirana zaštita</strong> — tretiraj kad je prag štetnosti prijeđen, ne „preventivno po kalendaru".</li>
    <li><strong>Voda</strong> — ne ostavljaj otvorene posude sa škropivom ni lokve od ispiranja prskalice; pčele dolaze piti vodu.</li>
    <li><strong>Susjedi</strong> — ako netko u blizini drži pčele, dogovorite se izravno; to rješava najviše problema.</li>
</ul>

<h2>Što ako dođe do trovanja</h2>
<p>
    Masovno ugibanje pčela ispred košnica nakon tretiranja pčelari prijavljuju inspekciji, a uzorci pčela i
    biljaka šalju se na analizu. Upravo tada je presudna uredna <strong>evidencija</strong>: datum, vrijeme, sredstvo,
    doza i parcela. Uz to se trovanje pčela kažnjava, a šteta se može tražiti od onoga tko ju je prouzročio.
</p>
