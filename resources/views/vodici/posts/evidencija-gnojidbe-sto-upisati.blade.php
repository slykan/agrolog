<h2>Kako voditi evidenciju da bude uredna</h2>
<ol>
    <li><strong>Upiši isti dan.</strong> Datum, parcela i količina zaboravljaju se brže nego što misliš, posebno u proljeće kad se gnoji na više parcela zaredom.</li>
    <li><strong>Po parceli, ne „ukupno za gospodarstvo".</strong> Kontrola gleda ARKOD parcelu.</li>
    <li><strong>Formulaciju gnojiva prepiši s vreće</strong> (npr. NPK 7-20-30), jer o njoj ovise kilogrami hraniva.</li>
    <li><strong>Čuvaj račune</strong> za kupljena gnojiva uz evidenciju.</li>
    <li><strong>Predaja gnoja drugima</strong> — ako višak stajskog gnoja daješ drugom gospodarstvu, imaj pisani dokaz o predaji.</li>
</ol>

