<p>
    Sredstva za zaštitu bilja na gospodarstvu su opasne tvari — za djecu, životinje, vodu i tebe. Zakon o održivoj
    uporabi pesticida propisuje kako ih čuvati, gdje pripremati škropivo i što s ostacima i praznom ambalažom.
    Većina pravila je zdrav razum, ali neke je lako previdjeti.
</p>

<h2>Gdje i kako čuvati sredstva</h2>
<ul>
    <li>U <strong>posebnoj prostoriji ili posebnom ormaru</strong>, zaključano i izvan dohvata djece.</li>
    <li>U <strong>originalnoj ambalaži</strong> s etiketom — nikad u bocama od pića ili neoznačenim posudama.</li>
    <li><strong>Odvojeno od hrane i hrane za životinje</strong>.</li>
    <li>Na temperaturi od <strong>5 do 30 °C</strong>, odnosno prema uvjetima s etikete — mraz i vrućina mogu uništiti formulaciju.</li>
    <li>Uz sredstva drži <strong>upijajući materijal</strong> (pijesak, perlit) za slučaj prolijevanja.</li>
</ul>
<div class="box-note">
    Dobra praksa: police od materijala koji ne upija, tekuća sredstva na donjim policama, prašiva iznad njih,
    i popis sredstava na vratima ormara — da se zna što je unutra ako zatreba hitna pomoć ili vatrogasci.
</div>

<h2>Priprema škropiva</h2>
<ul>
    <li>Škropivo pripremaj i prskalicu puni najmanje <strong>20 m od površinskih voda, izvora i bunara</strong>, osim ako etiketa ne propisuje drukčije.</li>
    <li>Pripremaj na podlozi s koje sredstvo ne može doći u tlo (npr. betonska ploča s odvodom u sabirnu jamu ili posebni plato).</li>
    <li>Koristi zaštitnu opremu s etikete — najmanje rukavice, a za koncentrat i zaštitu očiju.</li>
    <li>Pripremi samo onoliko koliko trebaš — <a href="{{ route('alat', 'kalkulator-skropiva') }}">kalkulator škropiva</a> izračuna i zadnje, nepuno punjenje.</li>
</ul>

<h2>Prskanje uz vode</h2>
<p>
    Pri primjeni sa zemlje uz vodotoke, bunare i jezera treba ostaviti <strong>netretirani pojas od najmanje 20 m</strong>,
    a pri primjeni iz zrakoplova 100 m, osim ako etiketa ili rješenje o registraciji ne propisuju drukčije. Ostatke
    škropiva nikad ne izlijevaj u vodu, kanal ili kanalizaciju.
</p>

<h2>Ostaci škropiva i pranje prskalice</h2>
<ol>
    <li>Ostatak u spremniku razrijedi čistom vodom i <strong>poprskaj po već tretiranoj površini</strong>, poštujući najveću dozu s etikete.</li>
    <li>Prskalicu operi na polju ili na platou, tako da voda od pranja ne dospije u površinske ni podzemne vode.</li>
    <li>Proliveno sredstvo pokupi upijajućim materijalom i zbrini kao opasni otpad.</li>
</ol>

<h2>Prazna ambalaža</h2>
<p>
    Prazna ambalaža i sredstva kojima je istekao rok smatraju se <strong>otpadom</strong> i zbrinjavaju se prema propisima
    o gospodarenju otpadom. U praksi:
</p>
<ul>
    <li>ambalažu tekućih sredstava odmah nakon pražnjenja <strong>isperi tri puta</strong> vodom i ispirak ulij u spremnik prskalice,</li>
    <li>probuši je da se ne bi ponovno koristila,</li>
    <li>predaj je u <strong>sabirne akcije ili ovlaštenom sakupljaču</strong> — informacije imaju poljoljekarne i komunalno poduzeće,</li>
    <li>nikad je ne pali, ne zakapaj i ne bacaj u miješani komunalni otpad.</li>
</ul>

<h2>Evidencija i susjedi</h2>
<p>
    Evidenciju o uporabi sredstava čuvaj najmanje <strong>tri godine</strong>, zajedno s računima o kupnji. Ako susjedi
    traže, obavijesti ih o tretiranju unaprijed, a zanošenje na susjedne parcele, kuće i bunare spriječi — po
    potrebi prekini prskanje. Kod sredstava opasnih za pčele vrijede dodatna pravila: vidi
    <a href="{{ route('vodic', 'zastita-pcela-pri-prskanju') }}">zaštita pčela pri prskanju</a>.
</p>

