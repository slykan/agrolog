<p>
    <strong>Karenca</strong> je najkraće propisano vrijeme između zadnje primjene sredstva za zaštitu bilja i berbe,
    žetve ili ispaše. U tom razdoblju ostaci sredstva se razgrađuju do razine koja je sigurna za potrošače. Berba
    prije isteka karence nije dopuštena.
</p>

<h2>Gdje pronaći karencu</h2>
<p>
    Karenca je navedena na <strong>etiketi</strong> i u uputi za uporabu sredstva, posebno za svaku kulturu — isto
    sredstvo može imati karencu od 7 dana za jednu, a 21 dan za drugu kulturu. Neka sredstva imaju oznaku da je
    karenca „osigurana vremenom primjene" (npr. primjena samo do određene faze razvoja).
</p>

