<h3>Više tretiranja i više sredstava</h3>
<p>
    Ako je kultura tretirana s više sredstava, računa se karenca za svako od njih od datuma njegove zadnje primjene,
    a berba je dopuštena tek kad isteknu <strong>sve</strong>. U praksi je mjerodavna ona koja ističe najkasnije.
</p>

<h2>Karenca i radna karenca nisu isto</h2>
<p>
    Osim karence, na etiketi se može naći i vrijeme ponovnog ulaska — koliko dugo nakon tretiranja ljudi ne bi
    smjeli ulaziti u tretirani nasad bez zaštitne opreme. To je zaštita radnika, a karenca je zaštita potrošača.
</p>

