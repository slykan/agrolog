<p>
    Tko profesionalno koristi sredstva za zaštitu bilja — a to je svaki poljoprivrednik koji ih primjenjuje u
    proizvodnji — mora imati završenu <strong>izobrazbu za sigurno rukovanje i pravilnu primjenu pesticida</strong>.
    Bez nje sredstva za profesionalnu uporabu ne možeš ni kupiti. Evo kako izobrazba izgleda, koliko vrijedi i
    kako je obnoviti.
</p>

<h2>Tko mora imati izobrazbu</h2>
<ul>
    <li><strong>profesionalni korisnici</strong> — poljoprivrednici i radnici koji primjenjuju pesticide,</li>
    <li>distributeri, odnosno prodavači u poljoljekarnama,</li>
    <li>savjetnici za zaštitu bilja.</li>
</ul>
<p>
    Pri kupnji u poljoljekarni prodavač provjerava tvoj status u središnjem informacijskom sustavu (FIS)
    Ministarstva poljoprivrede, a prodana količina upisuje se uz tvoje podatke.
</p>

<h2>Kako izgleda izobrazba</h2>
<table class="tbl">
    <tr><th>Modul</th><th>Trajanje</th><th>Za koga</th></tr>
    <tr><td>Osnovni</td><td>najmanje 17 školskih sati</td><td>prva izobrazba</td></tr>
    <tr><td>Dopunski</td><td>najmanje 5 školskih sati</td><td>obnova znanja</td></tr>
</table>
<p>
    Predavanja drže ovlašteni predavači kod ovlaštenih pružatelja izobrazbe. Na kraju je <strong>pisani ispit</strong>
    s 30 pitanja višestrukog izbora koja FIS nasumično dodjeljuje; ispit traje najviše 90 minuta, a za prolaz treba
    točno odgovoriti na najmanje <strong>70 %</strong> pitanja. Tko ne prođe, ponovno pristupa ispitu u roku od 14 dana,
    i to se može ponavljati.
</p>
<p>
    Nakon položenog ispita u FIS-u se automatski generira <strong>potvrda o završenoj izobrazbi</strong> s jedinstvenim
    barkodom, koju dok je aktivna možeš ispisati koliko god puta trebaš.
</p>

<h2>Što se uči</h2>
<p>Program izobrazbe okvirno obuhvaća:</p>
<ul>
    <li>propisi o pesticidima i odgovornost korisnika,</li>
    <li>opasnosti za zdravlje ljudi, okoliš, vode i pčele te prva pomoć,</li>
    <li>čitanje etikete, karenca, doze i miješanje,</li>
    <li>integrirana zaštita bilja i nekemijske mjere,</li>
    <li>rad sa strojevima, kalibracija i pregled prskalica,</li>
    <li>skladištenje, zbrinjavanje ambalaže i vođenje evidencije.</li>
</ul>

<h2>Obnova znanja svakih pet godina</h2>
<div class="box-note">
    Znanje se mora obnoviti <strong>u roku od pet godina</strong> od polaganja ispita.
</div>
<p>Obnoviti se može na tri načina:</p>
<ol>
    <li>dopunskom izobrazbom kod pružatelja izobrazbe,</li>
    <li>sudjelovanjem u odobrenom programu stručnog usavršavanja,</li>
    <li>stručnim tečajevima Ministarstva.</li>
</ol>
<p>
    Ako prođe više od pet godina, gubiš pravo koje izobrazba daje i moraš ponovno proći dopunsku izobrazbu i
    položiti ispit. Zato rok zapiši u kalendar — najbolje godinu dana unaprijed, jer termini kod pružatelja
    izobrazbe nisu svaki tjedan.
</p>

<h2>Praktični savjeti</h2>
<ul>
    <li>Provjeri svoj status prije sezone, ne u poljoljekarni na dan kad ti treba sredstvo.</li>
    <li>Ako na gospodarstvu prska više osoba (npr. član obitelji ili radnik), izobrazbu treba svaka od njih.</li>
    <li>Ono što naučiš o evidenciji odmah primijeni — vidi <a href="{{ route('vodic', 'elektronicka-evidencija-sredstava-za-zastitu-bilja') }}">elektronička evidencija sredstava za zaštitu bilja</a>.</li>
</ul>

<div class="box-warn">
    Propisi o izobrazbi mijenjaju se, a rok i načini obnove mogu se izmijeniti. Za svoj konkretni slučaj provjeri
    status u FIS-u ili kod savjetodavne službe.
</div>

